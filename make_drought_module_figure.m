function make_drought_module_figure(varargin)
% make_drought_module_figure  --  supplemental figure: how the drought module works
%
%   make_drought_module_figure
%   make_drought_module_figure('Region', 20, 'SSP', 'SSP2', 'DroughtScaleFactor', 0.30)
%
% WHAT IT SHOWS
% One panel: the annual agricultural yield factor for one region, 1985-2085,
% with the two forcing regimes drawn as visibly different objects.
%
%   1985-2022  OBSERVATION PERIOD. A single solid line. Deterministic here:
%              the GRMA secular trajectory perturbed by the OBSERVED ERA5
%              SPEI-6 record at each layer's harvest month. Every run of the
%              model sees this same series, so there is one line, no spread.
%
%   2023-2085  PROJECTION PERIOD. Faint lines, one per realisation. The
%              observed record ends in 2022, so variability is generated by
%              the two-state Markov chain, spatially correlated across regions
%              through a Gaussian copula.
%
%   Dashed     The secular trajectory (ensemble mean). The ONLY component
%              carrying a trend.
%
%   Dotted     The yield floors from utility_layers_v1.csv, at which
%              perturbations are clamped, so no drought drives yield to zero.
%
% ONE PANEL, NOT PER-CROP. createUtilityLayers returns agYF as
% nLocations x nYears -- the MEAN across the agricultural layers present in a
% location. An earlier version of this script drew one panel per crop from
% that same array, so the panels were identical and the crop labels wrong. A
% genuine per-crop figure requires yieldFactor (nLoc x nLayer x nYear) to be
% returned from createUtilityLayers.
%
% WHY IT CALLS THE MODEL
% Series come from the model's own createUtilityLayers, not a
% re-implementation, which would diverge the moment either changed.
%
% WHAT THE FIGURE ESTABLISHES
% (1) The 2023 step is a MODELLING SEAM, not a climatological one.
% (2) The chain is STATIONARY: the envelope neither widens nor drifts, so all
%     secular change comes from the dashed GRMA trajectory.
% (3) Drought PERSISTENCE is negative. For Androy the fitted p_DD is 0.154
%     against p_ND of 0.458 -- a drought year makes the next year LESS likely
%     to be dry. Recomputing p_DD directly from the raw observed record gives
%     0.154 as well, so the chain is correctly estimated; the property belongs
%     to the harvest-month SPEI-6 index, which samples one value per year from
%     a mean-reverting standardised series. Maximum observed run is two years,
%     twice in thirty-eight.
%
% CONSEQUENCE FOR THE PAPER. Consecutive-year drought is not the mechanism.
% What compounds is RECURRENCE OUTPACING RECOVERY: the buffer refills at
% bufferAccrualCapFrac (0.25) of cap per year, so ~3.2 years from the floor,
% while drought recurs every ~2.9 years at southern prevalence. The herd is
% chronically depleted. This also explains the cascadeContrast_south null --
% there are almost no consecutive-year cascades in the forcing to detect.

p = inputParser;
addParameter(p, 'Region', 19);                 % 19-21 = Androy, Anosy, Atsimo-Andrefana
% NReal   -- realisations COMPUTED, which set the ensemble mean.
% NShow   -- realisations DRAWN, kept small so individual trajectories stay
%            legible. The mean wants many draws; the eye wants few.
% Each realisation is a full createUtilityLayers call, which re-reads the GRMA
% and Markov CSVs, so 100 takes a few minutes. Worth it for a figure that goes
% in the paper; drop to 20 while iterating on layout.
addParameter(p, 'NReal',  100);
addParameter(p, 'NShow',  6);
addParameter(p, 'SSP',    'SSP5');
addParameter(p, 'EndYear', 2085);
% DROUGHT SCALE FACTOR. The first version of this script left it at the
% readParameters default of 0.10, which is NOT the calibrated value -- the
% Monte Carlo samples 0.05-0.40 and diagnostic traces have run at 0.30. Since
% the perturbation is delta = droughtScaleFactor * SPEI6, a figure drawn at
% 0.10 understates the model's inter-annual variability roughly threefold.
% Pass the value the campaign actually used.
addParameter(p, 'DroughtScaleFactor', 0.30);
addParameter(p, 'OutFile', './Outputs/fig_drought_module.png');
% EMBEDDING. Pass an existing axes to draw into it instead of a new figure,
% and Standalone false to suppress the export. Used by
% make_drought_workflow_figure to place this as panel (d).
addParameter(p, 'Axes',      []);
addParameter(p, 'Standalone', true);
% Y LIMITS. Default [0 1.05] leaves headroom for the two period annotations
% at y = 1.02. The assembler passes the SAME limits to this panel and to
% panel (a) so a reader can compare interannual variability against the
% secular trend without silently rescaling between them.
addParameter(p, 'YLim',      [0 1.05]);
parse(p, varargin{:});
opt = p.Results;

addpath('./Override_Core_MIDAS_Code');
addpath('./Application_Specific_MIDAS_Code');
addpath('./Core_MIDAS_Code');

% The scenario and horizon are read from the environment by readParameters,
% so set them here rather than editing the file.
setenv('MIDAS_SSP', opt.SSP);
setenv('MIDAS_END_YEAR', num2str(opt.EndYear));
setenv('DROUGHT_VARIABILITY', '1');

fprintf('Building world state for %s to %d (scaleFactor %.3f)...\n', ...
        opt.SSP, opt.EndYear, opt.DroughtScaleFactor);
[agentParameters, modelParameters, networkParameters, mapParameters] = ...
    readParameters(table( ...
        {'modelParameters.numAgents'; 'modelParameters.droughtScaleFactor'}, ...
        [50; opt.DroughtScaleFactor], ...
        'VariableNames', {'parameterNames', 'parameterValues'})); %#ok<ASGLU>

[locations, ~, ~, mapParameters] = createMapFromSHP(mapParameters); %#ok<ASGLU>

[locationLikelihood, genderLikelihood, ageLikelihood, survivalRate, ...
 fertilityRate, ageDiscountRateFactor, agePointsPopulation, ...
 agePointsSurvival, agePointsFertility, agePointsPref] = ...
    buildDemography(modelParameters, locations);
demographicVariables = struct( ...
    'locationLikelihood', locationLikelihood, 'genderLikelihood', genderLikelihood, ...
    'ageLikelihood', ageLikelihood, 'survivalRate', survivalRate, ...
    'fertilityRate', fertilityRate, 'ageDiscountRateFactor', ageDiscountRateFactor, ...
    'agePointsPopulation', agePointsPopulation, 'agePointsSurvival', agePointsSurvival, ...
    'agePointsFertility', agePointsFertility, 'agePointsPref', agePointsPref);

% ---- layer bookkeeping --------------------------------------------------
% agYF is returned as nLocations x nSimYears: the MEAN yield factor across
% the agricultural layers present in a location, not a per-crop series. The
% first version of this script drew one panel per crop from the same
% location-mean array, so the panels were identical and the crop labels were
% wrong. A genuine per-crop figure needs yieldFactor (nLoc x nLayer x nYear)
% returned from createUtilityLayers; until then this plots one honest panel.
L = readtable(modelParameters.utilityLayersFile, 'TextType', 'string');
hasFloor = ~isnan(L.drought_min_yield);
floorLo  = min(L.drought_min_yield(hasFloor));
floorHi  = max(L.drought_min_yield(hasFloor));

% REGION NAME. Resolved exactly as createUtilityLayers resolves it, because
% agYF is indexed by ROW POSITION in `locations` -- not by matrixID. The
% previous version looked up locations.matrixID == opt.Region, which matched
% nothing, silently fell back to the literal string "region 19", and so the
% GRMA lookup below could never find a matching row. The giveaway was the
% figure title reading "region 19" rather than "Androy".
if ismember('source_NAME_2', locations.Properties.VariableNames)
    locNamesGrma = string(locations.source_NAME_2);
elseif ismember('source_ADM2_FR', locations.Properties.VariableNames)
    locNamesGrma = string(locations.source_ADM2_FR);
else
    srcFlds = locations.Properties.VariableNames( ...
        startsWith(locations.Properties.VariableNames, 'source_'));
    locNamesGrma = string(locations.(srcFlds{1}));
end
regionName = char(locNamesGrma(opt.Region));
fprintf('Region %d resolves to "%s"\n', opt.Region, regionName);

% ---- realisations -------------------------------------------------------
fprintf('Drawing %d realisations...\n', opt.NReal);
nSimYears = opt.EndYear - modelParameters.startYear;
Y = nan(opt.NReal, nSimYears);

for r = 1:opt.NReal
    rng(r);
    [~, ~, ~, ~, ~, ~, ~, ~, ~, ~, ~, ~, ~, ~, ~, agYF] = ...
        createUtilityLayers(locations, modelParameters, demographicVariables);
    Y(r, :) = agYF(opt.Region, 1:nSimYears);
    if mod(r, 20) == 0; fprintf('  %d/%d\n', r, opt.NReal); end
end

% agYF column iCyc IS calendar year startYear + iCyc - 1
% (createUtilityLayers.m:304), so the offset is 0, not 1. This read
% startYear + (1:nSimYears) and labelled every drought year one year late.
years   = modelParameters.startYear + (0:nSimYears-1);
obsMask = years <= 2022;
prjMask = years >= 2023;

% ---- raw GRMA secular trend (no perturbation) ---------------------------
% Read straight from the GRMA yield CSVs so this line is the UNPERTURBED
% climatological surface. It is deliberately distinct from the ensemble mean
% plotted alongside it: the ensemble mean includes the stochastic
% perturbation, so the gap between the two lines IS the perturbation bias.
% Before the two-sided fix that gap was ~0.13 in the south, because normal
% years received no perturbation and the surface acted as a ceiling. It
% should now be close to zero, and this pair of lines is the quickest way to
% confirm that.
%
% The GRMA series is flat at the baseline value from 1985 to 2025, then
% piecewise linear through the 2050 and 2085 anchors (verified: -0.0046/yr
% then -0.0027/yr for Androy maize under SSP5).
%
% Layers are selected the way createUtilityLayers selects them: those with a
% grma_crop, present in this region under restrict_to. industrial_crop no
% longer qualifies -- it is wage labour and carries no crop yield factor.
grmaTrend = nan(1, nSimYears);
try
    inclCrops = strings(0);
    for iL = 1:height(L)
        gc = string(L.grma_crop(iL));
        if ismissing(gc) || gc == ""; continue; end
        rt = string(L.restrict_to(iL));
        if rt ~= "ALL" && ~contains(rt, regionName, 'IgnoreCase', true); continue; end
        inclCrops(end+1) = gc; %#ok<AGROW>
    end
    inclCrops = unique(inclCrops);
    fprintf('GRMA trend averaged over: %s\n', strjoin(cellstr(inclCrops), ', '));

    acc = zeros(1, nSimYears); nUsed = 0;
    for c = inclCrops
        fname = fullfile(fileparts(modelParameters.utilityLayersFile), ...
                         sprintf('GRMA_yield_%s_%s.csv', c, opt.SSP));
        if ~exist(fname, 'file')
            fprintf('  GRMA: missing %s\n', fname); continue;
        end
        % Read positionally, as createUtilityLayers does: column 1 is the
        % region name, columns 2:end are y1985..y2085. Going via a named
        % NAME_2 column and sprintf'd yNNNN column names is fragile, because
        % readtable can rename headers.
        T   = readtable(fname, 'TextType', 'string');
        rn  = string(T{:, 1});
        yd  = table2array(T(:, 2:end));
        idx = find(rn == string(regionName), 1);      % same comparison the model uses
        if isempty(idx)
            fprintf(['  GRMA: "%s" not found in %s\n        file has: %s ...\n'], ...
                    regionName, sprintf('GRMA_yield_%s_%s.csv', c, opt.SSP), ...
                    strjoin(cellstr(rn(1:min(4, numel(rn))))', ', '));
            continue;
        end
        v = nan(1, nSimYears);
        for iy = 1:nSimYears
            colIdx = years(iy) - 1985 + 1;            % firstYear fixed at 1985
            if colIdx >= 1 && colIdx <= size(yd, 2)
                v(iy) = yd(idx, colIdx);
            end
        end
        fprintf('  GRMA %-9s row %d (%s): %d of %d years\n', ...
                c, idx, rn(idx), sum(~isnan(v)), nSimYears);
        acc = acc + v; nUsed = nUsed + 1;
    end
    if nUsed > 0; grmaTrend = acc / nUsed; end
catch ME
    fprintf('GRMA trend not plotted: %s\n', ME.message);
end
fprintf('GRMA trend: %d crop file(s) used, %d of %d years non-NaN\n', ...
        max(nUsed, 0), sum(~isnan(grmaTrend)), nSimYears);

% ---- persistence diagnostic --------------------------------------------
% THE POINT OF THIS BLOCK. The Markov chain is correctly estimated -- p_DD
% recomputed from the raw observed record matches the fitted value to three
% decimals. But the observed harvest-month SPEI-6 series has NEGATIVE
% persistence: p_DD (0.154 for Androy) is well below p_ND (0.458), so a
% drought year makes the next year LESS likely to be dry. Maximum observed
% run is two years, twice in thirty-eight.
%
% Consequence: the projection cannot generate consecutive-year droughts, so
% "multi-year drought compounding" is not what drives the model. What does
% drive it is recurrence outpacing recovery -- the buffer refills at
% bufferAccrualCapFrac (0.25) of cap per year, taking ~3.2 years from the
% floor, while drought recurs every ~2.9 years at southern prevalence. The
% herd is chronically depleted. That is the defensible mechanism and it
% should be described that way rather than as consecutive bad years.
MP = readtable(modelParameters.droughtMarkovFile, 'TextType', 'string');
ref = MP(MP.layer == "rice_south", :);
fprintf('\n--- PERSISTENCE DIAGNOSTIC (%s) ---\n', regionName);
try
    row = ref(strcmpi(ref.region, regionName), :);
    if ~isempty(row)
        pDD = row.p_DD(1); pND = row.p_ND(1);
        fprintf('  fitted p_DD = %.3f, p_ND = %.3f\n', pDD, pND);
        fprintf('  expected drought run length = %.2f years\n', 1 / max(1 - pDD, eps));
        fprintf('  drought recurs every ~%.1f years; buffer refills in ~%.1f\n', ...
                1 / max(row.pi_D(1), eps), ...
                (1 - 0.2) / 0.25);
        if pDD < pND
            fprintf(['  NOTE: p_DD < p_ND -- negative persistence. Consecutive-year\n' ...
                     '  droughts are rarer than isolated ones. Compounding in this model\n' ...
                     '  comes from recurrence outpacing herd recovery, NOT from\n' ...
                     '  consecutive dry years.\n']);
        end
    end
catch
    fprintf('  (region name not matched in markov params -- skipped)\n');
end

% Realisation independence check: 40 independent chains should give an
% ensemble mean far smoother than any single member. If the mean wobbles as
% much as the members, the realisations are not varying.
sdMember = mean(std(diff(Y(:, prjMask), 1, 2), 0, 2));
sdMean   = std(diff(mean(Y(:, prjMask), 1), 1, 2));
fprintf('  mean |year-on-year change|: single realisation %.4f, ensemble mean %.4f\n', ...
        sdMember, sdMean);
fprintf('  ratio %.2f (expect ~sqrt(N)=%.1f if realisations are independent)\n', ...
        sdMember / max(sdMean, eps), sqrt(opt.NReal));

% ---- plot ---------------------------------------------------------------
if isempty(opt.Axes)
    fig = figure('Position', [100 100 1150 520], 'Color', 'w');
    ax  = axes(fig);
else
    ax  = opt.Axes;
    fig = ancestor(ax, 'figure');
end
hold(ax, 'on'); box(ax, 'on');
yl = opt.YLim;
% HandleVisibility off keeps the shading and the realisation lines OUT of the
% legend. legend('show') collects every object with a visible handle, so
% without this the patch and all NReal faint lines appear as data1...dataN.
patch(ax, [2023 opt.EndYear opt.EndYear 2023], [yl(1) yl(1) yl(2) yl(2)], ...
      [0.94 0.94 0.97], 'EdgeColor', 'none', 'HandleVisibility', 'off');

% Draw a readable subset, spread across the ensemble rather than the first
% NShow, so the sample is not systematically the low-seed realisations.
showIdx = unique(round(linspace(1, opt.NReal, min(opt.NShow, opt.NReal))));
for k = 1:numel(showIdx)
    % Name the first one only: the rest would repeat the same legend entry.
    if k == 1
        plot(ax, years(prjMask), Y(showIdx(k), prjMask), ...
             'Color', [0.30 0.45 0.70 0.45], 'LineWidth', 0.7, ...
             'DisplayName', sprintf('individual realisations (%d of %d shown)', ...
                                    numel(showIdx), opt.NReal));
    else
        plot(ax, years(prjMask), Y(showIdx(k), prjMask), ...
             'Color', [0.30 0.45 0.70 0.45], 'LineWidth', 0.7, ...
             'HandleVisibility', 'off');
    end
end
% DisplayName rather than a handle/label pair. Passing arrays to legend()
% relies on the two staying the same length, and when they drift MATLAB
% silently auto-labels the extras ("data3"). Naming each line at the point it
% is drawn makes that impossible, and legend('show') then picks up exactly
% the objects that carry a name.
plot(ax, years(obsMask), Y(1, obsMask), 'Color', [0.15 0.25 0.45], ...
     'LineWidth', 1.4, 'DisplayName', 'observed (deterministic)');
plot(ax, years, mean(Y, 1, 'omitnan'), '--', 'Color', [0.75 0.30 0.15], ...
     'LineWidth', 1.6, 'DisplayName', ...
     sprintf('ensemble mean (perturbed, n = %d)', opt.NReal));

% Only draw the trend if it actually has data. An all-NaN series still
% creates a Line object, which is what produced a legend entry with no
% visible line.
nGood = sum(~isnan(grmaTrend));
if nGood >= 2
    plot(ax, years, grmaTrend, '-.', 'Color', [0.10 0.45 0.30], ...
         'LineWidth', 1.2, 'DisplayName', 'GRMA secular trend (unperturbed)');
else
    fprintf(['WARNING: GRMA trend has only %d non-NaN points -- not plotted.\n' ...
             '         Check the region-name match reported above.\n'], nGood);
end
legend(ax, 'show', 'Location', 'southwest', 'Box', 'off', 'FontSize', 9);

% HandleVisibility off: yline/xline create ConstantLine objects, which
% legend() collects like any other graphics child. Their third argument is a
% Label, not a DisplayName, so they arrive in the legend unnamed -- which is
% where a stray "data3" entry comes from.
yline(ax, floorLo, ':', sprintf('lowest yield floor %.2f', floorLo), ...
      'Color', [0.35 0.35 0.35], 'LineWidth', 1.2, ...
      'LabelHorizontalAlignment', 'left', 'FontSize', 9, ...
      'HandleVisibility', 'off');
if floorHi ~= floorLo
    yline(ax, floorHi, ':', sprintf('highest yield floor %.2f', floorHi), ...
          'Color', [0.35 0.35 0.35], 'LineWidth', 1.2, ...
          'LabelHorizontalAlignment', 'left', 'FontSize', 9, ...
          'HandleVisibility', 'off');
end

xline(ax, 2022.5, '-', 'Color', [0.5 0.5 0.5], 'LineWidth', 1, ...
      'HandleVisibility', 'off');
% Annotations placed relative to yl, not at a hard-coded 1.02, so they stay
% inside the axes when the assembler passes shared limits.
yAnn = yl(1) + 0.97 * diff(yl);
text(ax, 2003, yAnn, 'observation period: observed ERA5 SPEI-6', ...
     'FontSize', 9, 'HorizontalAlignment', 'center');
text(ax, 2054, yAnn, 'projection period: stationary Markov chain', ...
     'FontSize', 9, 'HorizontalAlignment', 'center');
ylim(ax, yl); xlim(ax, [modelParameters.startYear opt.EndYear]);
xlabel(ax, 'year'); ylabel(ax, 'agricultural yield factor');
title(ax, sprintf('%s, %s -- mean across agricultural layers (droughtScaleFactor %.2f)', ...
      regionName, opt.SSP, opt.DroughtScaleFactor), 'FontWeight', 'normal');

if opt.Standalone && isempty(opt.Axes)
    exportgraphics(fig, opt.OutFile, 'Resolution', 200);
    fprintf('\nWrote %s\n', opt.OutFile);
end

% ---- numbers for the caption -------------------------------------------
obs = Y(1, obsMask); prj = Y(:, prjMask);
fprintf('\n--- caption figures ---\n');
fprintf('observed  mean %.3f  min %.3f\n', mean(obs, 'omitnan'), min(obs));
fprintf('projected mean %.3f  min %.3f  (across %d realisations)\n', ...
        mean(prj(:), 'omitnan'), min(prj(:)), opt.NReal);
fprintf('secular decline %.3f -> %.3f (%.0f%% of the starting value)\n', ...
        mean(Y(:, find(prjMask, 1)), 'omitnan'), mean(Y(:, end), 'omitnan'), ...
        100 * mean(Y(:, end), 'omitnan') / mean(Y(:, find(prjMask, 1)), 'omitnan'));
fprintf('projected region-years at or below the lowest floor: %.1f%%\n', ...
        100 * mean(prj(:) <= floorLo + 1e-9, 'omitnan'));

% PERTURBATION BIAS. The ensemble mean should now track the unperturbed GRMA
% trend closely. A persistent negative gap would mean the perturbation is
% still one-sided; before the 2026-09-03 fix it ran to about -0.13 in the
% south because normal years received no perturbation at all.
if any(~isnan(grmaTrend))
    gap = mean(Y, 1, 'omitnan') - grmaTrend;
    fprintf('\nperturbation bias (ensemble mean minus GRMA trend):\n');
    fprintf('  observation period %+.4f\n', mean(gap(obsMask), 'omitnan'));
    fprintf('  projection period  %+.4f   (was about -0.13 when one-sided)\n', ...
            mean(gap(prjMask), 'omitnan'));
end
end
