"""
derive_drought_markov_params.py
===============================
Regenerates the two derived drought inputs that MIDAS reads at runtime:

    Data/drought_markov_params.csv    two-state chain parameters and the
                                      per-state SPEI distributions, one row
                                      per region x agricultural layer
    Data/spei6_corr_<layer>.csv       22 x 22 inter-regional SPEI correlation
    Data/spei6_corr_shared.csv        mean of the per-layer matrices, which is
                                      what createUtilityLayers actually uses

WHY THIS EXISTS
readParameters.m has always claimed these files were "generated by
derive_drought_markov_params.py". That script was not in the repository. Both
files were therefore un-reproducible: nobody could regenerate them after a
change to utility_layers_v1.csv, and they silently went stale relative to it.
Written 2026-09-05, when moving cassava's SPEI sampling month from 7 to 3
made regeneration unavoidable.

INPUT IS THE OBSERVED TABLE, NOT THE RAW SPEI
Everything here derives from Data/observed_spei_harvest.csv, which
apply_observed_drought.py builds from CEDA_SPEI.csv at each layer's
drought_harvest_month. Run these two in order:

    python apply_observed_drought.py          # rebuilds observed_spei_harvest
    python derive_drought_markov_params.py    # rebuilds everything downstream

Deriving from the observed table rather than from CEDA directly guarantees
that the chain parameters describe exactly the series the model perturbs with.
An earlier arrangement where the two were built independently is how the
harvest-month change could have gone in with the Markov parameters still
describing the old window.

DEFINITIONS, matching Supplemental 2.4.3 and make_drought_state_panel.m
  drought year      SPEI-6 at the layer's sampling month <= DROUGHT_THRESHOLD
  p_DD              P(drought at t+1 | drought at t)
  p_ND              P(drought at t+1 | normal  at t)
  pi_D              stationary drought probability, p_ND / (1 - p_DD + p_ND)
  drought/normal
  spei mean & std   moments of the SPEI values within each state, which the
                    two-sided perturbation samples from

Ky (yield response to water stress) is not derived here -- it is an agronomic
constant carried through from the GRMA methodological report (AXA Climate /
Artelia / BRGM, January 2026, footnote 4): 1.2 maize, 1.2 cassava, 1.1 rice,
0.7 groundnut. It is written to the file for provenance; MIDAS does not read
it.

NOTE ON industrial_crop
The previous file carried industrial_crop rows at month 7. That layer's
drought columns were deliberately blanked when it was reclassified as wage
labour rather than smallholder production, so it has no sampling month and no
rows are written for it now. createUtilityLayers only looks up layers with a
grma_crop, so nothing reads them.
"""

import csv, os, statistics as st

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR   = os.path.join(SCRIPT_DIR, 'Data')
# VERSION-AWARE (2026-09-13). These three defaults reproduce the original v1
# behaviour exactly when the script is run with no arguments. The layer set,
# the observed table it derives from, and the outputs must all describe the
# SAME layer names -- drought_markov_params.csv and spei6_corr_shared.csv are
# both keyed by layer, so a v2 layer file with v1 derived files would leave the
# renamed layers with no Markov parameters and hence no projection-period
# drought variability at all.
#
#   python derive_drought_markov_params.py                        # v1
#   python derive_drought_markov_params.py --layers Data/utility_layers_v2.csv \
#          --obs Data/observed_spei_harvest_v2.csv --suffix _v2
OBS_CSV    = os.path.join(DATA_DIR, 'observed_spei_harvest.csv')
LAYERS_CSV = os.path.join(DATA_DIR, 'utility_layers_v1.csv')
OUT_SUFFIX = ''

DROUGHT_THRESHOLD = -0.5      # moderate drought, Vicente-Serrano et al. (2010)
KY = {'maize': 1.2, 'cassava': 1.2, 'rice': 1.1, 'peanut': 0.7}

MARKOV_COLS = ['region', 'layer', 'harvest_month', 'Ky', 'n_years',
               'drought_prevalence', 'p_DD', 'p_ND', 'pi_D',
               'drought_spei_mean', 'drought_spei_std',
               'normal_spei_mean', 'normal_spei_std',
               'n_drought_obs', 'n_normal_obs']


def load_layers():
    """Agricultural layers with a sampling month, in file order."""
    out = []
    with open(LAYERS_CSV, newline='') as f:
        for row in csv.DictReader(f):
            crop = (row.get('grma_crop') or '').strip()
            mth  = (row.get('drought_harvest_month') or '').strip()
            if crop and mth:
                out.append({'name': row['name'].strip(),
                            'crop': crop,
                            'month': int(float(mth))})
    if not out:
        raise SystemExit('no agricultural layers with a sampling month in '
                         + LAYERS_CSV)
    return out


def load_observed():
    """{layer: {region: {year: spei}}} from the observed harvest table."""
    with open(OBS_CSV, newline='') as f:
        rows = list(csv.reader(f))
    hdr, data = rows[0], rows[1:]
    series, regions = {}, [r[0] for r in data]
    for j, col in enumerate(hdr[1:], 1):
        layer, year = col.rsplit('_y', 1)
        year = int(year)
        for r in data:
            series.setdefault(layer, {}).setdefault(r[0], {})[year] = float(r[j])
    return series, regions


def chain_params(vals_by_year):
    """Two-state chain parameters and per-state moments for one series."""
    years = sorted(vals_by_year)
    v = [vals_by_year[y] for y in years]
    state = [x <= DROUGHT_THRESHOLD for x in v]

    dd = dn = nd = nn = 0
    for a, b in zip(state, state[1:]):
        if a and b:       dd += 1
        elif a and not b: dn += 1
        elif not a and b: nd += 1
        else:             nn += 1
    p_DD = dd / (dd + dn) if (dd + dn) else 0.0
    p_ND = nd / (nd + nn) if (nd + nn) else 0.0
    denom = 1 - p_DD + p_ND
    pi_D  = (p_ND / denom) if denom else 0.0

    d = [x for x in v if x <= DROUGHT_THRESHOLD]
    n = [x for x in v if x >  DROUGHT_THRESHOLD]
    m = lambda a: st.mean(a) if a else 0.0
    s = lambda a: st.stdev(a) if len(a) > 1 else 0.0
    return dict(n_years=len(v), drought_prevalence=len(d) / len(v),
                p_DD=p_DD, p_ND=p_ND, pi_D=pi_D,
                drought_spei_mean=m(d), drought_spei_std=s(d),
                normal_spei_mean=m(n),  normal_spei_std=s(n),
                n_drought_obs=len(d),   n_normal_obs=len(n))


def pearson(a, b):
    if len(a) < 2:
        return 0.0
    try:
        return st.correlation(a, b)
    except st.StatisticsError:      # zero variance
        return 0.0


def main():
    global OBS_CSV, LAYERS_CSV, OUT_SUFFIX
    import argparse
    ap = argparse.ArgumentParser(description='Derive drought Markov parameters.')
    ap.add_argument('--layers', default=LAYERS_CSV, help='utility layers CSV')
    ap.add_argument('--obs',    default=OBS_CSV,    help='observed SPEI harvest CSV')
    ap.add_argument('--suffix', default=OUT_SUFFIX,
                    help="appended to output filenames, e.g. '_v2'")
    a = ap.parse_args()
    LAYERS_CSV, OBS_CSV, OUT_SUFFIX = a.layers, a.obs, a.suffix
    for p in (LAYERS_CSV, OBS_CSV):
        if not os.path.exists(p):
            raise SystemExit(f'not found: {p}')

    layers = load_layers()
    series, regions = load_observed()
    print(f'layer file     : {LAYERS_CSV}')
    print(f'output suffix  : "{OUT_SUFFIX}"')
    print(f'observed table : {OBS_CSV}')
    print(f'layers         : ' +
          ', '.join(f"{l['name']}(m{l['month']})" for l in layers))

    # ---- Markov parameters -------------------------------------------
    rows = []
    for lay in layers:
        if lay['name'] not in series:
            raise SystemExit(f"layer {lay['name']} missing from {OBS_CSV} -- "
                             "re-run apply_observed_drought.py first")
        for reg in regions:
            p = chain_params(series[lay['name']][reg])
            rows.append([reg, lay['name'], lay['month'],
                         KY.get(lay['crop'], 1.0), p['n_years'],
                         round(p['drought_prevalence'], 4),
                         round(p['p_DD'], 4), round(p['p_ND'], 4),
                         round(p['pi_D'], 4),
                         round(p['drought_spei_mean'], 4),
                         round(p['drought_spei_std'], 4),
                         round(p['normal_spei_mean'], 4),
                         round(p['normal_spei_std'], 4),
                         p['n_drought_obs'], p['n_normal_obs']])
    rows.sort(key=lambda r: (r[1], r[0]))          # layer, then region
    out = os.path.join(DATA_DIR, f'drought_markov_params{OUT_SUFFIX}.csv')
    with open(out, 'w', newline='') as f:
        w = csv.writer(f); w.writerow(MARKOV_COLS); w.writerows(rows)
    print(f'\nwrote {out}  ({len(rows)} rows)')

    # ---- correlation matrices ----------------------------------------
    years = sorted(next(iter(series[layers[0]['name']].values())))
    mats = {}
    for lay in layers:
        S = series[lay['name']]
        cols = {r: [S[r][y] for y in years] for r in regions}
        M = [[pearson(cols[a], cols[b]) for b in regions] for a in regions]
        mats[lay['name']] = M
        p = os.path.join(DATA_DIR, f"spei6_corr_{lay['name']}.csv")
        with open(p, 'w', newline='') as f:
            w = csv.writer(f); w.writerow([''] + regions)
            for a, row in zip(regions, M):
                w.writerow([a] + [round(x, 6) for x in row])
        print(f'wrote {p}')

    n = len(regions)
    shared = [[sum(mats[l['name']][i][j] for l in layers) / len(layers)
               for j in range(n)] for i in range(n)]
    p = os.path.join(DATA_DIR, f'spei6_corr_shared{OUT_SUFFIX}.csv')
    with open(p, 'w', newline='') as f:
        w = csv.writer(f); w.writerow([''] + regions)
        for a, row in zip(regions, shared):
            w.writerow([a] + [round(x, 6) for x in row])
    print(f'wrote {p}  (mean of {len(layers)} layer matrices)')

    off = [shared[i][j] for i in range(n) for j in range(n) if i != j]
    print(f'\nshared matrix off-diagonal mean r = {sum(off)/len(off):+.4f} '
          f'(min {min(off):+.3f}, max {max(off):+.3f})')


if __name__ == '__main__':
    main()
